-- Contacts inherit their account's source, and expose the account's state/city (falling back to the contact's own).
-- 1) source: UPDATE contacts c SET source = a.source FROM accounts a WHERE a.id = c.account_id (done in 16 partitions);
--    contacts without account_id but with a matching domain take that account's source.
-- 2) view: state + city appended to contacts_view.
CREATE OR REPLACE VIEW contacts_view AS  SELECT c.id,
    c.account_id,
    c.first_name,
    c.last_name,
    c.email,
    c.title,
    c.linkedin_url,
    c.phone,
    c.country,
    c.created_at,
    c.updated_at,
    c.company_name,
    c.full_name,
    c.phone2,
    c.location,
    c.email_status,
    c.validated_at,
    c.hubspot_excluded,
    c.vertical,
    c.domain,
    c.linkedin_checked_at,
    c.validated_company,
    c.parent_company,
    c.sdr_owner,
    a.name AS account_name,
    a.domain AS account_domain,
    a.industry,
    a.sub_industry,
    a.employee_range,
    a.revenue_range,
    a.vertical AS account_vertical,
    c.marked_irrelevant,
    c.marked_irrelevant_by,
    c.marked_irrelevant_at,
    c.source,
    c.debounce_fail_count,
    c.hubspot_lifecycle_stage,
    c.hubspot_lead_status,
    c.hubspot_matched_at,
    a.account_type,
    (c.customer OR COALESCE(a.customer, false)) AS customer,
    c.verticals,
    c.match_domain,
    a.industry_category,
    a.industry_subcategory,
    a.employee_bucket,
    a.revenue_bucket,
    a.monthly_revenue_bucket,
    a.platform,
    c.name_rank,
    COALESCE(a.state, c.state) AS state,
    COALESCE(a.city, c.city) AS city
   FROM (contacts c
     LEFT JOIN accounts a ON ((c.account_id = a.id)));
